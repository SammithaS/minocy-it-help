/**
 * Runs a promptfoo suite with telemetry off, then appends a summary to evals/RESULTS.md.
 *   pnpm eval            # all suites
 *   pnpm eval retrieval  # one suite
 */
import { spawnSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";

const SUITES = ["retrieval"] as const;
const wanted = process.argv.slice(2);
const suites = wanted.length ? SUITES.filter((s) => wanted.includes(s)) : SUITES;

interface Component {
  pass: boolean;
  assertion?: { metric?: string };
}
interface Row {
  vars: Record<string, string>;
  success: boolean;
  response?: { output?: string };
  gradingResult?: { componentResults?: Component[] };
}

mkdirSync("evals/results", { recursive: true });
const sections: string[] = [];
let failed = false;

for (const suite of suites) {
  const out = `evals/results/${suite}.json`;
  const res = spawnSync(
    "pnpm",
    ["exec", "promptfoo", "eval", "-c", `evals/${suite}.yaml`, "--no-cache", "--max-concurrency", "4", "--no-progress-bar", "--no-table", "-o", out],
    { stdio: "inherit", shell: true, env: { ...process.env, PROMPTFOO_DISABLE_TELEMETRY: "1", PROMPTFOO_DISABLE_UPDATE: "1" } },
  );
  if (!existsSync(out) || res.error) {
    console.error(`✗ ${suite}: promptfoo didn't produce results (exit ${res.status ?? "?"})`);
    process.exit(1);
  }
  const rows: Row[] = JSON.parse(readFileSync(out, "utf8")).results.results;
  const metrics = new Map<string, { pass: number; total: number }>();
  const misses: string[] = [];
  for (const r of rows) {
    for (const c of r.gradingResult?.componentResults ?? []) {
      const name = c.assertion?.metric;
      if (!name) continue;
      // Skip metrics that don't apply to this case (no-guide only applies to out-of-scope rows, etc.).
      const applies = name === "no-guide" ? r.vars.expected === "none" : r.vars.expected !== "none";
      if (!applies) continue;
      const m = metrics.get(name) ?? { pass: 0, total: 0 };
      m.total++;
      if (c.pass) m.pass++;
      metrics.set(name, m);
      if (!c.pass) {
        const ids = (() => {
          try {
            return (JSON.parse(r.response?.output ?? "{}") as { ids?: string[] }).ids?.join(", ");
          } catch {
            return "?";
          }
        })();
        misses.push(`| ${name} | ${r.vars.query} | ${r.vars.expected} | ${ids ?? ""} |`);
      }
    }
    if (!r.success) failed = true;
  }
  const pct = (m: { pass: number; total: number }) => `${((100 * m.pass) / m.total).toFixed(1)}% (${m.pass}/${m.total})`;
  const summary = [...metrics].map(([k, v]) => `| ${k} | ${pct(v)} |`).join("\n");
  console.log(`\n${suite}:\n${[...metrics].map(([k, v]) => `  ${k}: ${pct(v)}`).join("\n")}`);
  sections.push(
    `## ${suite}\n\n| Metric | Score |\n|---|---|\n${summary}\n\n` +
      (misses.length ? `Misses:\n\n| Metric | Query | Expected | Got (top 5) |\n|---|---|---|---|\n${misses.join("\n")}\n` : "No misses.\n"),
  );
}

const date = new Date().toISOString().slice(0, 16).replace("T", " ");
writeFileSync(
  "evals/RESULTS.md",
  `# Eval results\n\nGenerated by \`pnpm eval\` on ${date} UTC. Raw output: \`evals/results/*.json\` (git-ignored).\n\n${sections.join("\n")}`,
);
console.log("\nWrote evals/RESULTS.md");
process.exit(failed ? 1 : 0);
